    public static function forSlug(string $slug): self
    {
        $page = static::query()->where('slug', $slug)->first();

        if ($page) {
            return $page;
        }

        return new static([
            'slug'    => $slug,
            'title'   => static::defaultTitle($slug),
            'content' => static::defaultsFor($slug),
        ]);
    }

